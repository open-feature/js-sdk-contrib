/**
 * Records which revision of open-feature/spec the conformance artifacts came from, as TypeScript.
 *
 * A conformance report has to name the revision it ran against or two reports cannot be compared,
 * and the `spec/` submodule is **not** part of the published npm package -- `nx package` copies the
 * artifacts out of it and leaves the git metadata behind. So the answer is captured here, at build
 * time, rather than read from git at run time.
 *
 * It runs from the `pullSpec` target, which both `test` and `package` depend on, so the recorded
 * revision is refreshed by the same command that checks the submodule out. The generated file is
 * committed: a plain `jest` invocation does not go through Nx, and an adopter building from a source
 * tree without git should still get a truthful answer rather than a compile error.
 *
 * The commit is all that is recorded. The tree hash of the asset directory used to be recorded
 * alongside it, to identify the artifacts independently of unrelated specification commits, but the
 * results stream now carries every executed feature file verbatim as a `Source` message -- which
 * identifies the artifacts by their content, covers only the files that actually ran, and is checked
 * by the report's own digest.
 *
 * Usage:
 *
 *   node scripts/write-revision.js       # from libs/shared/tck
 *   nx pullSpec tck             # from the workspace root
 */

const { execFileSync } = require('node:child_process');
const { existsSync, writeFileSync } = require('node:fs');
const { join, resolve } = require('node:path');

/** Where the artifacts live inside the specification repository. */
const ASSETS_PATH_IN_SPEC = 'specification/assets/provider-tck';

const libRoot = resolve(__dirname, '..');
const specRoot = join(libRoot, 'spec');
const outputPath = join(libRoot, 'src', 'lib', 'revision.ts');

function gitOutput(args) {
  return execFileSync('git', args, { cwd: libRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
}

/**
 * Reads the commit from the submodule.
 *
 * Returns `undefined` -- rather than throwing -- when git is not installed or the submodule is not
 * checked out. Neither is a reason to fail a build: the committed file already holds the answer, and
 * overwriting it with a guess would be worse than leaving it alone.
 */
function readRevision() {
  // join() takes POSIX segments and produces a native path, so the constant stays readable and this
  // works unchanged on Windows.
  if (!existsSync(join(specRoot, ...ASSETS_PATH_IN_SPEC.split('/')))) {
    return undefined;
  }
  try {
    return gitOutput(['-C', specRoot, 'rev-parse', 'HEAD']);
  } catch (error) {
    process.stderr.write(`write-revision: could not read the spec revision from git: ${error.message}\n`);
    return undefined;
  }
}

const template = (revision) => `// Code generated by scripts/write-revision.js. DO NOT EDIT.
//
// Regenerate with \`nx pullSpec tck\`, which both checks out the
// open-feature/spec submodule and rewrites this file from it.

/** The open-feature/spec commit the conformance artifacts in \`spec/\` were taken from. */
export const SPEC_REVISION = '${revision}';
`;

const revision = readRevision();

if (!revision) {
  const explanation = existsSync(outputPath)
    ? `keeping the committed ${outputPath}`
    : `writing an empty ${outputPath}; conformance reports from this build will say the spec revision is unknown`;
  process.stderr.write(
    `write-revision: the spec submodule at ${specRoot} is unavailable or has no git metadata -- ${explanation}.\n` +
      `write-revision: run 'git submodule update --init libs/shared/tck/spec' from the workspace root.\n`,
  );
  if (!existsSync(outputPath)) {
    writeFileSync(outputPath, template(''), 'utf8');
  }
  process.exit(0);
}

if (!/^[0-9a-f]{40}$/.test(revision)) {
  process.stderr.write(`write-revision: git returned an implausible commit ${JSON.stringify(revision)}\n`);
  process.exit(1);
}

writeFileSync(outputPath, template(revision), 'utf8');
process.stdout.write(`write-revision: spec ${revision.slice(0, 12)}\n`);
